// Builds js/icons-data.js from the Tabler icon set (https://tabler.io/icons, MIT licence).
// It includes every icon named in the Notion tables (Jobs, Structures) plus the ones the interface uses.
// Usage: node tools/make-icons.js   (needs: npm install @tabler/icons)
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
globalThis.Krowns = {};
require(path.join(root, 'data/game-data.js'));
const D = globalThis.Krowns.data;

const names = new Set(['heart', 'bolt', 'meat', 'yin-yang', 'barbell', 'hourglass', 'crown', 'users', 'flame', 'droplet', 'zzz', 'x', 'player-play', 'player-pause',
  'player-track-next', 'refresh', 'zoom-in', 'zoom-out', 'history', 'list-details', 'volume', 'volume-off', 'dice-5', 'current-location', 'tools-kitchen-2', 'apple',
  'moon', 'sun', 'clock', 'focus-2', 'info-circle', 'chevron-down', 'chevron-up', 'coins', 'wood', 'wheat', 'grave-2', 'skull', 'sword', 'heartbeat', 'user', 'help-circle', 'backpack']);
for (const j of Object.values(D.jobs)) if (j.icon) names.add(j.icon);
for (const s of Object.values(D.structures)) if (s.icon) names.add(s.icon);

const dirs = [process.env.TABLER_DIR, '/tmp/krowns-work/npm/node_modules/@tabler/icons/icons/outline', path.join(root, 'node_modules/@tabler/icons/icons/outline')].filter(Boolean);
const dir = dirs.find((d) => fs.existsSync(d));
if (!dir) throw new Error('Tabler icons not found. Run: npm install @tabler/icons');
const out = {};
for (const n of [...names].sort()) {
  const f = path.join(dir, n + '.svg');
  if (!fs.existsSync(f)) { console.warn('icon not found: ' + n); continue; }
  const svg = fs.readFileSync(f, 'utf8');
  const inner = svg.replace(/^[\s\S]*?class="[^"]*"\s*>/, '').replace(/<\/svg>\s*$/, '').replace(/<path stroke="none"[^>]*\/>/, '').replace(/\s+/g, ' ').trim();
  out[n] = inner;
}
fs.writeFileSync(path.join(root, 'js/icons-data.js'),
  '// Generated by tools/make-icons.js from Tabler Icons (MIT). Do not edit by hand.\n(function () {\n  const K = (globalThis.Krowns = globalThis.Krowns || {});\n  K.icons = ' + JSON.stringify(out) + ';\n  K.icon = function (name, size, color) {\n    const inner = K.icons[name] || K.icons["help-circle"];\n    return \'<svg xmlns="http://www.w3.org/2000/svg" width="\' + (size || 16) + \'" height="\' + (size || 16) + \'" viewBox="0 0 24 24" fill="none" stroke="\' + (color || "currentColor") + \'" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\' + inner + "</svg>";\n  };\n})();\n');
console.log('js/icons-data.js written with ' + Object.keys(out).length + ' icons');
