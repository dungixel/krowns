// Builds js/icons.js from the full Tabler icon set in assets/icons.
// Run: node tools/make-icons.js     (only needed if you change the list below)
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');

const outline = ['crown', 'building-castle', 'flame', 'droplet', 'swords', 'sword', 'skull', 'x', 'spiral', 'wheat', 'bread',
  'meat', 'feather', 'wand', 'chef-hat', 'bow', 'player-play', 'player-pause', 'player-track-next', 'refresh', 'volume',
  'volume-off', 'heart', 'messages', 'plant', 'paw', 'users', 'heart-broken', 'hourglass', 'sparkles', 'book', 'info-circle',
  'arrows-maximize', 'leaf', 'bolt', 'ghost', 'shield', 'chevron-down', 'chevron-up', 'flag', 'cross', 'tool'];
const filled = ['heart', 'crown', 'flame'];

function inner(file) {
  const svg = fs.readFileSync(file, 'utf8');
  const m = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/);
  if (!m) throw new Error('bad svg ' + file);
  return m[1].replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/, '').replace(/\s+/g, ' ').trim();
}

const data = { outline: {}, filled: {} };
for (const n of outline) {
  const f = path.join(root, 'assets/icons/outline', n + '.svg');
  if (!fs.existsSync(f)) throw new Error('missing outline icon ' + n);
  data.outline[n] = inner(f);
}
for (const n of filled) {
  const f = path.join(root, 'assets/icons/filled', n + '.svg');
  if (!fs.existsSync(f)) throw new Error('missing filled icon ' + n);
  data.filled[n] = inner(f);
}

const out = `// Krowns - icons from Tabler Icons (https://tabler.io/icons, MIT licence).
// GENERATED by tools/make-icons.js from the full set in assets/icons/. Do not edit by hand.
(function () {
  const K = (globalThis.Krowns = globalThis.Krowns || {});
  const DATA = ${JSON.stringify(data)};
  const cache = {};

  // Inline <svg> markup that takes the surrounding text colour.
  function svg(name, opts) {
    opts = opts || {};
    const size = opts.size || 16;
    const variant = opts.variant === 'filled' ? 'filled' : 'outline';
    const body = (DATA[variant] || {})[name] || DATA.outline[name] || '';
    const attrs = variant === 'filled'
      ? 'fill="currentColor"'
      : 'fill="none" stroke="currentColor" stroke-width="' + (opts.stroke || 2) + '" stroke-linecap="round" stroke-linejoin="round"';
    return '<svg xmlns="http://www.w3.org/2000/svg" width="' + size + '" height="' + size + '" viewBox="0 0 24 24" ' + attrs +
      ' class="ic ' + (opts.cls || '') + '" aria-hidden="true">' + body + '</svg>';
  }

  // An <img> for drawing the icon on the canvas in a fixed colour. Cached.
  function image(name, color, variant, stroke) {
    const key = name + '|' + color + '|' + (variant || 'outline') + '|' + (stroke || 2);
    if (cache[key]) return cache[key];
    const v = variant === 'filled' ? 'filled' : 'outline';
    const body = (DATA[v] || {})[name] || '';
    const attrs = v === 'filled'
      ? 'fill="' + color + '"'
      : 'fill="none" stroke="' + color + '" stroke-width="' + (stroke || 2) + '" stroke-linecap="round" stroke-linejoin="round"';
    const text = '<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 24 24" ' + attrs + '>' + body + '</svg>';
    const img = new Image();
    img.src = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(text);
    cache[key] = img;
    return img;
  }

  K.icons = { svg, image, names: Object.keys(DATA.outline) };
})();
`;
fs.writeFileSync(path.join(root, 'js/icons.js'), out);
console.log('wrote js/icons.js with', outline.length, 'outline +', filled.length, 'filled icons');
